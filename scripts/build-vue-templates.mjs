import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {dirname,join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {parse,compileTemplate} from 'vue/compiler-sfc';

// Only repository templates enter the compiler. Never compile API data or browser DOM.
export const vuePages=[['index','app'],['permission-catalog','permissionCatalog'],['role-access-matrix','matrixApp']];
export const vueRuntimeUrl='/assets/vue.js?v=20261102-a03-csp';
const require=createRequire(import.meta.url);
const vueDir=dirname(require.resolve('vue/package.json'));

export async function vueArtifacts(){
  const result=new Map();
  for(const [page,id] of vuePages){
    const filename=`public/${page}.html`,html=await readFile(filename,'utf8');
    // SFC parser exposes compiler-dom's HTML AST, including exact source offsets.
    const {descriptor,errors}=parse(`<template>${html}</template>`,{filename,ignoreEmpty:false});
    if(errors.length)throw new Error(`${filename}: ${errors.join('; ')}`);
    const ast=descriptor.template.ast;
    const find=node=>node.type===1&&node.props?.some(p=>p.type===6&&p.name==='id'&&p.value?.content===id)?node:(node.children||[]).map(find).find(Boolean);
    const root=find(ast);
    if(!root)throw new Error(`Missing Vue root ${id} in ${filename}`);
    const outer=root.loc.source,source=outer.slice(outer.indexOf('>')+1,outer.lastIndexOf('</'));
    const compiled=compileTemplate({source,filename,id:`gentia-${id}`,transformAssetUrls:false,compilerOptions:{runtimeModuleName:vueRuntimeUrl,isCustomElement:tag=>tag==='record-audit'}});
    if(compiled.errors.length)throw new Error(`${filename}: ${compiled.errors.join('; ')}`);
    result.set(`public/generated/${page}-render.js`,`// Generated by scripts/build-vue-templates.mjs. Do not edit.\n${compiled.code}\n`);
  }
  result.set('public/assets/vue.js',await readFile(join(vueDir,'dist/vue.runtime.esm-browser.prod.js'),'utf8'));
  result.set('public/assets/VUE-LICENSE.txt',await readFile(join(vueDir,'LICENSE'),'utf8'));
  return result;
}

if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
  const check=process.argv.includes('--check');
  for(const [file,content] of await vueArtifacts()){
    if(check){if(await readFile(file,'utf8')!==content)throw new Error(`Stale Vue artifact: ${file}`);}
    else{const existing=await readFile(file,'utf8').catch(()=>null);if(existing!==content){await mkdir(dirname(file),{recursive:true});await writeFile(file,content);}}
  }
  console.log(check?'Vue artifacts match trusted templates.':'Compiled three trusted templates and copied matching runtime-only Vue.');
}
